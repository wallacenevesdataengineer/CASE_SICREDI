SELECT 20 TOP,
        C.NOME AS CLIENTE,
        C.SEGMENTO,
        COUNT(T.VALOR) AS QTD_TRANSACOES,
        SUM(T.VALOR) AS VALOR_TOTAL,
        AVG(T.VALOR) AS TICKET_MEDIO
FROM FATO_TRANSACAO T 
JOIN DIM_CLIENTE C 
ON T.ID_CLIENTE = C.ID_CLIENTE
JOIN DIM_CALENDARIO CAL 
ON T.ID_TEMPO = CAL.ID_ID_TEMPO
WHERE CAL.DATA_TRANSACAO >= DATEDIFF(DAY,-90,GETDATE())
GROUP BY C.NOME,C.SEGMENTO
ORDER BY VALOR_TOTAL DESC;

