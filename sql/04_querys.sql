SELECT  C.NOME AS CLIENTE,
        C.SEGMENTO,
        G.NOME_GERENTE,
        A.NOME_AGENCIA, 
        C.CLASS_RISCO ,
        T.TIPO_TRANSACAO,
        CAL.DATA_TRANSACAO
FROM FATO_TRANSACAO T 
JOIN DIM_CLIENTE C
ON T.ID_CLIENTE = C.ID_CLIENTE 
JOIN DIM_CALENDARIO CAL
ON T.ID_TEMPO = CAL.ID_TEMPO 
JOIN BRIGDE_CLIENTE_GERENTE BG 
ON C.ID_CLIENTE = BG.ID_CLIENTE 
JOIN DIM_GERENTE G 
ON BG.ID_GERENTE  = G.ID_GERENTE 
JOIN DIM_AGENCIA A 
ON G.ID_AGENCIA = A.ID_AGENCIA
WHERE BG.DATA_INICIO BETWEEN BG.DATA_FIM
