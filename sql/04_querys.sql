SELECT C.NOME AS CLIENTE,
       DATEPART(YEAR,CAL.DATA_TRANSACAO) AS ANO,
       DATEPART(MONTH,CAL.DATA_TRANSACAO) AS MES, 
       AVG(FS.SALDO) AS SALDO_MEDIO,
       COUNT(T.ID_FATO_TRANSACAO) AS QTD_TRANSACOES_PIX,
       SUM(T.VALOR_TRANSACAO) AS VALOR_TOTAL_PIX
FROM FATO_SALDO FS 
JOIN DIM_CLIENTE C
ON FS.ID_CLIENTE = C.ID_CLIENTE 
JOIN FATO_TRANSACAO T 
ON FS.ID_CLIENTE = T.ID_CLIENTE 
JOIN DIM_CALENDARIO CAL 
ON T.ID_TEMPO = CAL.ID_TEMPO 
WHERE T.TIPO_TRANSACAO = 'PIX'
AND T.VALOR_TRANSACAO >= 5000 
GROUP BY  C.NOME, DATEPART(YEAR,CAL.DATA_TRANSACAO),DATEPART(MONTH,CAL.DATA_TRANSACAO)
HAVING AVG(FS.SALDO) > 10000
AND COUNT(T.ID_FATO_TRANSACAO) > 10 
ORDER BY SALDO_MEDIO DESC;
