    PRAZO INT,
    QTD_PARCELAS INT,
    VENCIMENTO DATE,
    STATUS VARCHAR(50),
    ATRASOS VARCHAR(50),
    NEGOCIACOES VARCHAR(50),
    LIQUIDACAO_ANTECIPADA VARCHAR(100),
    REFINAMENTO VARCHAR(100),
    INADIMPLENCIA VARCHAR(100)
);


CREATE TABLE DIM_CAMPANHA(
    ID_CAMPANHA INT IDENTITY(1,1) PRIMARY KEY 
    NOME_CAMPANHA VARCHAR(100),
    TIPO_CAMPANHA VARCHAR(100),
    DATA_INICIO DATE,
