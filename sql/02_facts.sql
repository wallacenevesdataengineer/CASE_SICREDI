CREATE TABLE FATO_TRANSACAO (
    ID_FATO_TRANSACAO INT IDENTITY(1,1) PRIMARY KEY,
    ID_CLIENTE INT,
    ID_CONTA INT,
    ID_CONTA_ORIGEM INT,
    ID_CONTA_DESTINO INT,
    ID_CANAL INT,
    ID_CALENDARIO INT,
    --ID_TIPO_TRANSACAO INT,
    TIPO_TRANSACAO VARCHAR(100),
    ID_LOCALIZACAO INT,
    ID_TEMPO INT,
    ID_CREDITO INT,
    DATA DATE,
    HORARIO DATETIME,
    VALOR_TRANSACAO DECIMAL(18,2),
    MOEDA DECIMAL(18,2),
    STATUS VARCHAR(50),
    SALDO_TRANSACAO DECIMAL(18,2),
    DISPOSITIVO VARCHAR(200),
    TICKET_MEDIO DECIMAL(18,2),
    FOREIGN KEY (ID_CLIENTE) REFERENCES DIM_CLIENTE(ID_CLIENTE),
    FOREIGN KEY (ID_CONTA) REFERENCES DIM_CONTA(ID_CONTA),
    FOREIGN KEY (ID_CANAL) REFERENCES DIM_CANAL(ID_CANAL),
    FOREIGN KEY (ID_CALENDARIO) REFERENCES DIM_CALENDARIO(ID_CALENDARIO),
    --FOREIGN KEY (ID_TIPO_TRANSACAO) REFERENCES DIM_TIPO_TRANSACAO(ID_TIPO_TRANSACAO),
    FOREIGN KEY (ID_LOCALIZACAO) REFERENCES DIM_LOCALIZACAO(ID_LOCALIZACAO),
    FOREIGN KEY (ID_TEMPO) REFERENCES DIM_TEMPO(ID_TEMPO),
    FOREIGN KEY (ID_CREDITO) REFERENCES DIM_CREDITO(ID_CREDITO),
);

